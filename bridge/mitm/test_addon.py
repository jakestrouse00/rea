"""Offline tests for the generated REA mitmproxy structure-stream addon.

The addon module is generated by `bridge/mitm/generate_addon.ts` and then
imported here; `mitmproxy` itself is not installed, so the module-level import
falls back and every hook is exercised with local fakes. No proxy starts and no
socket is opened.
"""

import importlib.util
import io
import json
import os
import shutil
import stat
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from urllib.parse import parse_qsl

REPOSITORY = Path(__file__).resolve().parents[2]
GENERATOR = REPOSITORY / "bridge" / "mitm" / "generate_addon.ts"


def load_addon(directory):
    path = Path(directory) / "rea_mitm_addon.py"
    spec = importlib.util.spec_from_file_location("rea_mitm_addon", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class MultiHeaders:
    def __init__(self, pairs=()):
        self._pairs = [(name, value) for name, value in pairs]

    def __setitem__(self, name, value):
        self.__delitem__(name)
        self._pairs.append((name, value))

    def __delitem__(self, name):
        self._pairs = [
            (key, value) for key, value in self._pairs if key.lower() != name.lower()
        ]

    def __contains__(self, name):
        return any(key.lower() == name.lower() for key, _ in self._pairs)

    def get(self, name, default=None):
        for key, value in self._pairs:
            if key.lower() == name.lower():
                return value
        return default

    def keys(self):
        return [key for key, _ in self._pairs]

    def items(self, multi=False):
        if multi:
            return list(self._pairs)
        seen = {}
        for key, value in self._pairs:
            seen.setdefault(key.lower(), value)
        return list(seen.items())


class Query:
    def __init__(self, pairs=()):
        self._pairs = list(pairs)

    def __setitem__(self, name, value):
        self.__delitem__(name)
        self._pairs.append((name, value))

    def __delitem__(self, name):
        self._pairs = [(key, value) for key, value in self._pairs if key != name]

    def __contains__(self, name):
        return any(key == name for key, _ in self._pairs)


class Message:
    def __init__(self, method="GET", headers=(), content=b"", status=None):
        self.method = method
        self.headers = MultiHeaders(headers)
        self.content = content
        self.status_code = status
        self.scheme = "https"
        self.host = "api.example.test"
        self.port = 443


class Flow:
    def __init__(self, request, response=None, path="/v1/items/42", query="page=2"):
        self.request = request
        self.response = response
        self.metadata = {}
        self.request.pretty_url = "https://api.example.test:443" + path + (
            "?" + query if query else ""
        )
        self.request.query = Query(parse_qsl(query, keep_blank_values=True))


@unittest.skipIf(shutil.which("node") is None, "node is required to generate the addon")
class AddonTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.directory = tempfile.mkdtemp(prefix="rea-mitm-addon-")
        subprocess.run(
            ["node", str(GENERATOR), "--out", cls.directory, "--force"],
            check=True,
            cwd=REPOSITORY,
            capture_output=True,
            text=True,
        )
        cls.addon = load_addon(cls.directory)

    def setUp(self):
        self.hold = tempfile.mkdtemp(prefix="rea-mitm-hold-")
        self.control = os.path.join(self.hold, "rules.json")
        os.environ["REA_MITM_HOLD_DIR"] = self.hold
        os.environ["REA_MITM_CONTROL_PATH"] = self.control
        os.environ["REA_MITM_LISTEN_HOST"] = "127.0.0.1"
        os.environ["REA_MITM_LISTEN_PORT"] = "8080"
        self.addon._STATE.update(
            {"sequence": 0, "control_mtime": None, "control_revision": None, "notices": set()}
        )
        self.addon._STATE.pop("rules", None)
        self.buffer = io.StringIO()
        self.previous_stdout = sys.stdout
        sys.stdout = self.buffer

    def tearDown(self):
        sys.stdout = self.previous_stdout
        for name in (
            "REA_MITM_HOLD_DIR",
            "REA_MITM_CONTROL_PATH",
            "REA_MITM_LISTEN_HOST",
            "REA_MITM_LISTEN_PORT",
        ):
            os.environ.pop(name, None)
        shutil.rmtree(self.hold, ignore_errors=True)

    def frames(self):
        return [json.loads(line) for line in self.buffer.getvalue().splitlines() if line]

    def test_the_generator_is_idempotent(self):
        result = subprocess.run(
            ["node", str(GENERATOR), "--out", self.directory, "--check"],
            cwd=REPOSITORY,
            capture_output=True,
            text=True,
        )
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_path_templates_classify_value_segments(self):
        template, parameters = self.addon._path_template(
            "/v1/users/42/0b4f5d4c-1a52-4f7f-9a0e-9f9a1a0b3c4d/items"
        )
        self.assertEqual(
            template,
            "/v1/users/{integer}/{uuid}/items",
        )
        self.assertEqual(
            [(entry["name"], entry["type"]) for entry in parameters],
            [("path_3", "integer"), ("path_4", "uuid")],
        )

    def test_query_and_body_parameters_report_names_only(self):
        self.assertEqual(
            [(entry["name"], entry["type"]) for entry in self.addon._query_parameters("page=2&name=bob")],
            [("page", "integer"), ("name", "string")],
        )
        document = json.dumps({"email": "a@b.test", "count": 2, "tags": []}).encode()
        self.assertEqual(
            [(entry["name"], entry["type"]) for entry in self.addon._body_parameters(document, "application/json")],
            [("email", "string"), ("count", "integer"), ("tags", "array")],
        )

    def test_shape_sketch_is_bounded_and_value_free(self):
        sketch = self.addon._sketch({"id": "secret", "items": [{"a": 1}]})
        self.assertEqual(sketch["kind"], "object")
        self.assertEqual([key["name"] for key in sketch["keys"]], ["id", "items"])
        self.assertNotIn("secret", json.dumps(sketch))
        self.assertEqual(self.addon._sketch("x"), {"kind": "scalar", "type": "string"})

    def test_content_type_classes_match_the_closed_vocabulary(self):
        cases = {
            "application/json; charset=utf-8": "json",
            "text/html": "html",
            "application/octet-stream": "binary",
            "image/png": "image",
            "nonsense": "unknown",
        }
        for media_type, expected in cases.items():
            self.assertEqual(
                self.addon._content_type_class(MultiHeaders([("content-type", media_type)])),
                expected,
            )
        self.assertEqual(self.addon._content_type_class(MultiHeaders()), "absent")

    def test_a_captured_flow_retains_bodies_and_streams_structure(self):
        addon = self.addon.ReaMitmAddon()
        request = Message(
            method="POST",
            headers=[("authorization", "Bearer secret"), ("content-type", "application/json")],
            content=b'{"a":1}',
        )
        flow = Flow(request)
        response = Message(status=201, headers=[("content-type", "application/json")], content=b'{"id":"x"}')
        flow.response = response

        addon.request(flow)
        addon.response(flow)

        frames = self.frames()
        kinds = [frame["type"] for frame in frames]
        self.assertEqual(kinds, ["flow"])
        emitted = frames[0]
        streamed = json.dumps(emitted)
        self.assertNotIn("Bearer secret", streamed)
        self.assertNotIn('{"a":1}', streamed)
        self.assertNotIn("id\":\"x", streamed)
        self.assertEqual(emitted["request"]["header_names"], ["authorization", "content-type"])
        self.assertEqual(emitted["request"]["path_template"], "/v1/items/{integer}")
        self.assertEqual(emitted["request"]["parameters"][0]["name"], "path_3")
        self.assertEqual(emitted["response"]["status"], 201)
        self.assertEqual(emitted["response"]["shape"]["kind"], "object")
        request_hold = emitted["request"]["body_hold"]
        response_hold = emitted["response"]["body_hold"]
        self.assertEqual(Path(request_hold["path"]).read_bytes(), b'{"a":1}')
        self.assertEqual(Path(response_hold["path"]).read_bytes(), b'{"id":"x"}')
        for hold in (request_hold, response_hold):
            self.assertEqual(stat.S_IMODE(os.stat(hold["path"]).st_mode), 0o600)
        record = json.loads(Path(emitted["entry"]["path"]).read_text())
        self.assertEqual(record["method"], "POST")
        self.assertEqual(record["headers"], [["authorization", "Bearer secret"], ["content-type", "application/json"]])
        self.assertEqual(stat.S_IMODE(os.stat(emitted["entry"]["path"]).st_mode), 0o600)

    def test_a_request_rule_rewrites_headers_and_query(self):
        Path(self.control).write_text(
            json.dumps(
                {
                    "version": 1,
                    "revision": 1,
                    "rules": [
                        {
                            "rule_id": "0b4f5d4c-1a52-4f7f-9a0e-9f9a1a0b3c4d",
                            "phase": "request",
                            "match": {"path_prefixes": ["/v1"]},
                            "action": {
                                "kind": "request",
                                "set_headers": [["x-probe", "1"]],
                                "remove_headers": ["authorization"],
                                "set_query": [["debug", "1"]],
                                "remove_query": [],
                            },
                            "expires_at": 9_999_999_999_999,
                        }
                    ],
                }
            )
        )
        addon = self.addon.ReaMitmAddon()
        request = Message(headers=[("authorization", "Bearer secret")])
        flow = Flow(request)
        addon.request(flow)
        self.assertEqual(flow.request.headers.get("x-probe"), "1")
        self.assertNotIn("authorization", flow.request.headers)
        self.assertIn("debug", flow.request.query)
        matches = [frame for frame in self.frames() if frame["type"] == "rule_match"]
        self.assertEqual(len(matches), 1)
        self.assertEqual(matches[0]["headers_changed"], 2)
        self.assertEqual(matches[0]["query_changed"], 1)
        self.assertEqual(matches[0]["phase"], "request")

    def test_a_response_rule_replaces_status_and_body(self):
        import base64

        Path(self.control).write_text(
            json.dumps(
                {
                    "version": 1,
                    "revision": 1,
                    "rules": [
                        {
                            "rule_id": "5d0e1a44-6b2f-4be1-8f0e-3f5f6a7b8c9d",
                            "phase": "response",
                            "match": {"methods": ["GET"]},
                            "action": {
                                "kind": "response",
                                "set_headers": [],
                                "remove_headers": [],
                                "status": 418,
                                "body_base64": base64.b64encode(b"teapot").decode(),
                            },
                            "expires_at": 9_999_999_999_999,
                        }
                    ],
                }
            )
        )
        addon = self.addon.ReaMitmAddon()
        flow = Flow(Message())
        flow.response = Message(
            status=200,
            headers=[("content-type", "text/plain"), ("content-length", "2")],
            content=b"ok",
        )
        addon.request(flow)
        addon.response(flow)
        self.assertEqual(flow.response.status_code, 418)
        self.assertEqual(flow.response.content, b"teapot")
        self.assertNotIn("content-length", flow.response.headers)
        matches = [frame for frame in self.frames() if frame["type"] == "rule_match"]
        self.assertEqual(matches[0]["status_before"], 200)
        self.assertEqual(matches[0]["status_after"], 418)
        self.assertTrue(matches[0]["body_replaced"])

    def test_an_unreadable_control_file_keeps_the_previous_rules_and_notices_once(self):
        Path(self.control).write_text("not json")
        addon = self.addon.ReaMitmAddon()
        flow = Flow(Message())
        addon.request(flow)
        addon.request(Flow(Message()))
        notices = [frame for frame in self.frames() if frame["type"] == "notice"]
        self.assertEqual(len(notices), 1)
        self.assertEqual(notices[0]["reason"], "control-unreadable")

    def test_the_startup_advertisement_matches_the_reas_contract(self):
        self.addon.ReaMitmAddon().running()
        ready = self.frames()[0]
        self.assertEqual(ready["type"], "ready")
        self.assertEqual(ready["protocol"], 1)
        self.assertEqual(ready["addon"], {"id": "rea-mitm-addon", "version": 1})
        self.assertEqual(ready["listen"], {"host": "127.0.0.1", "port": 8080})


if __name__ == "__main__":
    unittest.main()
