#!/usr/bin/env node
/**
 * Generate the REA mitmproxy structure-stream addon.
 *
 * Usage:
 *   node bridge/mitm/generate_addon.ts --out <absolute-directory> [--force]
 *   node bridge/mitm/generate_addon.ts --out <absolute-directory> --check
 *
 * The addon speaks the JSON-lines protocol `src/domain/mitm/mitmStream.ts`
 * parses. It streams structure only: origins, methods, path templates,
 * parameter names and type classes, header names, status counts, and a bounded
 * response-shape sketch. Request and response bodies are written to the
 * session's owner-only capture directory and never appear on stdout.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { isAbsolute, join, resolve } from "node:path";

const ADDON_FILE_NAME = "rea_mitm_addon.py";

const ADDON_SOURCE = String.raw`"""REA mitmproxy structure-stream addon.

Generated by bridge/mitm/generate_addon.ts; do not edit by hand.

REA spawns mitmdump with this script and reads one JSON object per line from
stdout. Bodies are retained in REA_MITM_HOLD_DIR (owner-only) and named by the
frames that reference them, so no body or header value reaches the stream.
Standing rewrite rules are read from REA_MITM_CONTROL_PATH.
"""

import base64
import hashlib
import json
import os
import re
import sys
import time
from urllib.parse import parse_qsl, urlsplit

try:
    from mitmproxy import version as mitmproxy_version
    _MITMPROXY_VERSION = mitmproxy_version.VERSION
except Exception:  # pragma: no cover - the addon refuses no proxy build
    _MITMPROXY_VERSION = "unknown"

PROTOCOL = 1
ADDON_ID = "rea-mitm-addon"
ADDON_VERSION = 1

MAX_LINE_HEADER_NAMES = 64
MAX_PARAMETERS = 32
MAX_SHAPE_KEYS = 24
MAX_SHAPE_DEPTH = 3
MAX_ENTRY_BYTES = 1024 * 1024
MAX_BODY_BYTES = 64 * 1024 * 1024

TEXTUAL_MEDIA = (
    "application/json",
    "application/xml",
    "application/x-www-form-urlencoded",
    "application/javascript",
)

DEFAULT_PORTS = {"http": 80, "https": 443}
INT_SEGMENT = re.compile(r"^[0-9]{1,20}$")
UUID_SEGMENT = re.compile(
    r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$"
)
HEX_SEGMENT = re.compile(r"^[0-9a-fA-F]{16,}$")

_STATE = {"sequence": 0, "control_mtime": None, "control_revision": None, "notices": set()}


def _emit(event):
    try:
        sys.stdout.write(json.dumps(event, ensure_ascii=True, separators=(",", ":")) + "\n")
        sys.stdout.flush()
    except Exception:
        pass


def _notice(reason, message):
    key = (reason, message)
    if key in _STATE["notices"] or len(_STATE["notices"]) >= 64:
        return
    _STATE["notices"].add(key)
    _emit({"type": "notice", "reason": reason, "message": message[:512]})


def _hold_dir():
    return os.environ.get("REA_MITM_HOLD_DIR") or ""


def _control_path():
    return os.environ.get("REA_MITM_CONTROL_PATH") or ""


def _write_private(path, data):
    """Write exact bytes owner-only, replacing only a missing or stale path."""
    temporary = path + ".tmp"
    descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(descriptor, "wb") as handle:
        handle.write(data)
    os.replace(temporary, path)
    return {"path": path, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}


def _retain(kind, sequence, content):
    """Retain body bytes as an owner-only file; never emit their content."""
    if content is None or len(content) == 0:
        return None
    if len(content) > MAX_BODY_BYTES:
        _notice("body-unwritable", "A body exceeded the retained-bytes budget and was not written.")
        return None
    directory = _hold_dir()
    if directory == "":
        _notice("body-unwritable", "REA_MITM_HOLD_DIR is unset, so bodies cannot be retained.")
        return None
    target = os.path.join(directory, "bodies", str(sequence) + "." + kind + ".bin")
    try:
        os.makedirs(os.path.dirname(target), exist_ok=True)
        return _write_private(target, bytes(content))
    except Exception as error:
        _notice("body-unwritable", "A body could not be retained: " + type(error).__name__)
        return None


def _origin(flow):
    scheme = (flow.request.scheme or "http").lower()
    host = flow.request.host or ""
    port = flow.request.port
    if port is None or port == DEFAULT_PORTS.get(scheme):
        return scheme + "://" + host
    return scheme + "://" + host + ":" + str(port)


def _path_and_query(flow):
    try:
        parts = urlsplit(flow.request.pretty_url)
        return parts.path or "/", parts.query or ""
    except Exception:
        path = flow.request.path or "/"
        if "?" in path:
            head, _, tail = path.partition("?")
            return head or "/", tail
        return path, ""


def _segment_type(segment):
    if INT_SEGMENT.match(segment):
        return "integer"
    if UUID_SEGMENT.match(segment):
        return "uuid"
    if HEX_SEGMENT.match(segment):
        return "hex"
    return None


def _path_template(path):
    parameters = []
    segments = path.split("/")
    rendered = []
    position = 0
    for segment in segments:
        if segment == "":
            rendered.append(segment)
            continue
        position += 1
        kind = _segment_type(segment)
        if kind is None:
            rendered.append(segment)
            continue
        rendered.append("{" + kind + "}")
        parameters.append({"name": "path_" + str(position), "location": "path", "type": kind})
    return "/".join(rendered) or "/", parameters


def _value_type(value):
    if isinstance(value, bool):
        return "boolean"
    if value is None:
        return "null"
    if isinstance(value, int):
        return "integer"
    if isinstance(value, float):
        return "number"
    if isinstance(value, list):
        return "array"
    if isinstance(value, dict):
        return "object"
    return "string"


def _query_parameters(query):
    parameters = []
    try:
        pairs = parse_qsl(query, keep_blank_values=True)
    except Exception:
        return parameters
    for name, value in pairs[:MAX_PARAMETERS]:
        if any(entry["name"] == name for entry in parameters):
            continue
        parameters.append(
            {"name": name, "location": "query", "type": "integer" if INT_SEGMENT.match(value) else "string"}
        )
    return parameters


def _json_object(content, media_type):
    if "json" not in media_type or len(content) > MAX_ENTRY_BYTES:
        return None
    try:
        decoded = json.loads(content.decode("utf-8", errors="strict"))
    except Exception:
        return None
    return decoded if isinstance(decoded, dict) else None


def _body_parameters(content, media_type):
    document = _json_object(content, media_type)
    if document is None:
        return []
    parameters = []
    for name, value in list(document.items())[:MAX_PARAMETERS]:
        parameters.append({"name": str(name)[:256], "location": "body", "type": _value_type(value)})
    return parameters


def _sketch(value, depth=0):
    if depth >= MAX_SHAPE_DEPTH:
        return {"kind": "truncated", "deeper": True}
    if isinstance(value, dict):
        keys = []
        truncated = False
        for index, (name, item) in enumerate(value.items()):
            if index >= MAX_SHAPE_KEYS:
                truncated = True
                break
            keys.append({"name": str(name)[:256], "type": _value_type(item)})
        return {"kind": "object", "keys": keys, "truncated": truncated}
    if isinstance(value, list):
        items = None if depth + 1 >= MAX_SHAPE_DEPTH else len(value)
        item = _sketch(value[0], depth + 1) if value else None
        return {"kind": "array", "items": items, "item": item, "truncated": items is None}
    return {"kind": "scalar", "type": _value_type(value)}


def _response_shape(content, media_type):
    if content is None:
        return None
    if "json" in media_type:
        try:
            return _sketch(json.loads(content.decode("utf-8", errors="strict")))
        except Exception:
            return None
    if media_type in TEXTUAL_MEDIA or media_type.startswith("text/"):
        return {"kind": "scalar", "type": "string"}
    return {"kind": "scalar", "type": "bytes"}


def _content_type_class(headers):
    value = headers.get("content-type")
    if value is None:
        return "absent"
    media_type = value.split(";")[0].strip().lower()
    if "/" not in media_type:
        return "unknown"
    main, _, sub = media_type.partition("/")
    if sub == "json" or sub.endswith("+json"):
        return "json"
    if main == "text":
        if sub == "html":
            return "html"
        if sub == "xml" or sub.endswith("+xml"):
            return "xml"
        if sub in ("javascript", "ecmascript"):
            return "javascript"
        if sub == "css":
            return "css"
        return "text"
    if main == "application":
        if sub == "xml" or sub.endswith("+xml"):
            return "xml"
        if sub in ("javascript", "x-javascript"):
            return "javascript"
        if sub == "x-www-form-urlencoded":
            return "text"
        return "binary"
    if main == "image":
        return "image"
    if main in ("audio", "video"):
        return "audio_video"
    if main == "font":
        return "font"
    if main == "multipart":
        return "multipart"
    return "unknown"


def _header_names(headers):
    names = []
    for name in headers.keys():
        lowered = name.lower()[:256]
        if lowered in names:
            continue
        names.append(lowered)
        if len(names) >= MAX_LINE_HEADER_NAMES:
            break
    return names


def _media_type(headers):
    return (headers.get("content-type") or "").split(";")[0].strip().lower()


def _entry_record(flow, sequence, request_body, response_body):
    """Write the replayable request as an owner-only record."""
    directory = _hold_dir()
    if directory == "":
        return None
    try:
        body = bytes(flow.request.content or b"")
        held = None
        if len(body) > 0 and request_body is not None:
            held = request_body
        record = {
            "version": 1,
            "sequence": sequence,
            "method": flow.request.method.upper(),
            "url": flow.request.pretty_url,
            "headers": [[name, value] for name, value in flow.request.headers.items(multi=True)],
            "body": {
                "path": None if held is None else held["path"],
                "bytes": len(body),
                "sha256": None if held is None else held["sha256"],
            },
            "response": None
            if flow.response is None
            else {
                "status": flow.response.status_code,
                "body": {
                    "path": None if response_body is None else response_body["path"],
                    "bytes": 0 if flow.response.content is None else len(flow.response.content),
                    "sha256": None if response_body is None else response_body["sha256"],
                },
            },
        }
        content = json.dumps(record, ensure_ascii=True, separators=(",", ":")).encode("utf-8")
        if len(content) > MAX_ENTRY_BYTES:
            _notice("entry-unwritable", "A replayable entry record exceeded its byte budget.")
            return None
        target = os.path.join(directory, "entries", str(sequence) + ".json")
        os.makedirs(os.path.dirname(target), exist_ok=True)
        return _write_private(target, content)
    except Exception as error:
        _notice("entry-unwritable", "A replayable entry could not be written: " + type(error).__name__)
        return None


def _load_control():
    """Read the control file when its mtime changes; keep the previous rules."""
    path = _control_path()
    if path == "":
        return []
    try:
        stats = os.stat(path)
    except OSError:
        return _STATE.get("rules", [])
    stamp = (stats.st_mtime_ns, stats.st_size)
    if _STATE["control_mtime"] == stamp:
        return _STATE.get("rules", [])
    _STATE["control_mtime"] = stamp
    try:
        with open(path, "r", encoding="utf-8") as handle:
            document = json.load(handle)
        if document.get("version") != 1 or not isinstance(document.get("rules"), list):
            raise ValueError("unknown control document")
        revision = int(document.get("revision", 0))
        now_ms = int(time.time() * 1000)
        rules = [rule for rule in document["rules"] if int(rule.get("expires_at", 0)) > now_ms]
        _STATE["rules"] = rules
        _STATE["control_revision"] = revision
        return rules
    except Exception as error:
        _notice("control-unreadable", "The rule control file could not be read: " + type(error).__name__)
        return _STATE.get("rules", [])


def _matches(rule, flow, origin, path, method):
    match = rule.get("match") or {}
    origins = match.get("origins") or []
    if origins and origin not in origins:
        return False
    prefixes = match.get("path_prefixes") or []
    if prefixes and not any(path.startswith(prefix) for prefix in prefixes):
        return False
    methods = match.get("methods") or []
    if methods and method not in [entry.upper() for entry in methods]:
        return False
    return bool(origins or prefixes or methods)


def _apply_rules(flow, rules, phase, sequence):
    origin = _origin(flow)
    path, _ = _path_and_query(flow)
    method = (flow.request.method or "").upper()
    template, _ = _path_template(path)
    for rule in rules:
        action = rule.get("action") or {}
        if action.get("kind") != phase:
            continue
        if not _matches(rule, flow, origin, path, method):
            continue
        headers_changed = 0
        query_changed = 0
        body_replaced = False
        status_before = None if flow.response is None else flow.response.status_code
        status_after = status_before
        try:
            target = flow.request if phase == "request" else flow.response
            if target is None:
                continue
            for name, value in action.get("set_headers") or []:
                target.headers[name] = value
                headers_changed += 1
            for name in action.get("remove_headers") or []:
                if name in target.headers:
                    del target.headers[name]
                    headers_changed += 1
            if phase == "request":
                for name, value in action.get("set_query") or []:
                    flow.request.query[name] = value
                    query_changed += 1
                for name in action.get("remove_query") or []:
                    if name in flow.request.query:
                        del flow.request.query[name]
                        query_changed += 1
            if action.get("body_base64") is not None:
                target.content = base64.b64decode(action["body_base64"])
                for framing in ("content-length", "transfer-encoding"):
                    if framing in target.headers:
                        del target.headers[framing]
                body_replaced = True
            if phase == "response" and action.get("status") is not None:
                flow.response.status_code = int(action["status"])
                status_after = flow.response.status_code
        except Exception as error:
            _emit(
                {
                    "type": "error",
                    "reason": "rule-application",
                    "message": ("A rewrite rule failed: " + type(error).__name__)[:512],
                }
            )
        _emit(
            {
                "type": "rule_match",
                "rule_id": rule.get("rule_id"),
                "phase": phase,
                "method": method[:32],
                "origin": origin[:255],
                "path_template": template[:8192],
                "status_before": status_before,
                "status_after": status_after,
                "headers_changed": headers_changed,
                "query_changed": query_changed,
                "body_replaced": body_replaced,
            }
        )


def _duration_ms(flow):
    try:
        started = float(flow.metadata.get("rea_started") or 0)
    except (TypeError, ValueError):
        return 0
    if started <= 0:
        return 0
    return max(0, int((time.time() - started) * 1000))


class ReaMitmAddon:
    def running(self):
        host = os.environ.get("REA_MITM_LISTEN_HOST") or "127.0.0.1"
        try:
            port = int(os.environ.get("REA_MITM_LISTEN_PORT") or "8080")
        except ValueError:
            port = 8080
        _emit(
            {
                "type": "ready",
                "protocol": PROTOCOL,
                "addon": {"id": ADDON_ID, "version": ADDON_VERSION},
                "mitmproxy": {"version": str(_MITMPROXY_VERSION)},
                "listen": {"host": host, "port": port},
            }
        )

    def request(self, flow):
        try:
            _STATE["sequence"] += 1
            flow.metadata["rea_sequence"] = _STATE["sequence"]
            flow.metadata["rea_started"] = time.time()
            rules = _load_control()
            _apply_rules(flow, rules, "request", _STATE["sequence"])
        except Exception as error:
            _emit(
                {
                    "type": "error",
                    "reason": "request-hook",
                    "message": ("The request hook failed: " + type(error).__name__)[:512],
                }
            )

    def response(self, flow):
        try:
            sequence = int(flow.metadata.get("rea_sequence") or 0)
            if sequence == 0:
                _STATE["sequence"] += 1
                sequence = _STATE["sequence"]
            rules = _load_control()
            _apply_rules(flow, rules, "response", sequence)
            self._emit_flow(flow, sequence)
        except Exception as error:
            _emit(
                {
                    "type": "error",
                    "reason": "response-hook",
                    "message": ("The response hook failed: " + type(error).__name__)[:512],
                }
            )

    def error(self, flow):
        try:
            sequence = int(flow.metadata.get("rea_sequence") or 0)
            if sequence == 0:
                _STATE["sequence"] += 1
                sequence = _STATE["sequence"]
            self._emit_flow(flow, sequence)
        except Exception as error:
            _emit(
                {
                    "type": "error",
                    "reason": "error-hook",
                    "message": ("The error hook failed: " + type(error).__name__)[:512],
                }
            )

    def _emit_flow(self, flow, sequence):
        request = flow.request
        request_media = _media_type(request.headers)
        request_body = _retain("req", sequence, request.content)
        response = flow.response
        response_body = None
        response_facts = None
        if response is not None:
            response_media = _media_type(response.headers)
            response_body = _retain("res", sequence, response.content)
            response_facts = {
                "status": response.status_code,
                "header_names": _header_names(response.headers),
                "content_type_class": _content_type_class(response.headers),
                "body_bytes": 0 if response.content is None else len(response.content),
                "body_hold": response_body,
                "shape": _response_shape(response.content, response_media),
            }
        path, query = _path_and_query(flow)
        template, path_parameters = _path_template(path)
        parameters = path_parameters + _query_parameters(query) + _body_parameters(request.content, request_media)
        entry = _entry_record(flow, sequence, request_body, response_body)
        _emit(
            {
                "type": "flow",
                "sequence": sequence,
                "at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                "duration_ms": _duration_ms(flow),
                "request": {
                    "method": (request.method or "GET").upper()[:32],
                    "origin": _origin(flow)[:255],
                    "path_template": template[:8192],
                    "header_names": _header_names(request.headers),
                    "parameters": parameters[:MAX_PARAMETERS],
                    "content_type_class": _content_type_class(request.headers),
                    "body_bytes": 0 if request.content is None else len(request.content),
                    "body_hold": request_body,
                },
                "response": response_facts,
                "entry": entry,
            }
        )
`;

interface Options {
  readonly out: string;
  readonly force: boolean;
  readonly check: boolean;
}

const usage = (): never => {
  process.stderr.write(
    "usage: node bridge/mitm/generate_addon.ts --out <absolute-directory> [--force|--check]\n",
  );
  process.exit(2);
};

const parse = (argv: readonly string[]): Options => {
  let out: string | undefined;
  let force = false;
  let check = false;
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--out") {
      out = argv[index + 1];
      index += 1;
      continue;
    }
    if (argument === "--force") {
      force = true;
      continue;
    }
    if (argument === "--check") {
      check = true;
      continue;
    }
    usage();
  }
  if (out === undefined || !isAbsolute(out)) usage();
  return { out, force, check };
};

const main = (): void => {
  const options = parse(process.argv.slice(2));
  const directory = resolve(options.out);
  const target = join(directory, ADDON_FILE_NAME);
  if (options.check) {
    if (!existsSync(target)) {
      process.stderr.write(`missing generated addon: ${target}\n`);
      process.exit(1);
    }
    if (readFileSync(target, "utf8") !== ADDON_SOURCE) {
      process.stderr.write(`generated addon is stale: ${target}\n`);
      process.exit(1);
    }
    return;
  }
  if (existsSync(target) && !options.force) {
    process.stderr.write(`refusing to replace ${target} without --force\n`);
    process.exit(1);
  }
  mkdirSync(directory, { recursive: true });
  writeFileSync(target, ADDON_SOURCE, { encoding: "utf8", mode: 0o644 });
  process.stdout.write(`${target}\n`);
};

main();
